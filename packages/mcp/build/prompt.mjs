// Bundle packages/mcp/prompts/**/*.md into one generated constant file,
// packages/mcp/src/guides/AutoMovieGuideConstant.ts, gitignored and rebuilt on
// every install/build. The unified AutoMovieApplication exposes each document
// by exact SCREAMING_SNAKE_CASE name through getGuideDocument({ name }).
// One file, one export.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PACKAGE_ROOT = resolve(HERE, "..");
const PROMPTS_ROOT = resolve(PACKAGE_ROOT, "prompts");
const OUT_DIR = resolve(PACKAGE_ROOT, "src/guides");
const OUT_FILE = resolve(OUT_DIR, "AutoMovieGuideConstant.ts");
mkdirSync(OUT_DIR, { recursive: true });

// The corpus is grouped in folders, one per topic area, exactly as the skills
// are. A guide joins the served set by existing under `prompts/`, so a document
// nobody wired is impossible rather than merely unlikely; `README.md` is the
// corpus's own note to its maintainers and is the one file that never serves.
const guideFiles = (directory) =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const full = resolve(directory, entry.name);
    if (entry.isDirectory()) return guideFiles(full);
    if (entry.name === "README.md" || !entry.name.endsWith(".md")) return [];
    return [full];
  });

// An area's index is `INDEX.md` and serves under the area's own name, so the
// folder and the guide an agent asks for are one word rather than two that have
// to be kept in step. The corpus root is the exception with a reason: its index
// is the constitution, and `AUTOMOVIE_OVERALL` is the name every gate refusal,
// guide, and diagnostic already tells an agent to read.
const guideName = (file) => {
  const stem = basename(file, ".md");
  if (stem !== "INDEX") return stem;
  const area = basename(dirname(file));
  return area === "prompts"
    ? "AUTOMOVIE_OVERALL"
    : area.replaceAll("-", "_").toUpperCase();
};

const files = guideFiles(PROMPTS_ROOT).sort();

const record = {};
for (const file of files) {
  const name = guideName(file);
  if (!/^[A-Z][A-Z0-9_]*$/.test(name))
    throw new Error(
      `Prompt file "${file}" does not name a SCREAMING_SNAKE_CASE guide (expected e.g. review/INDEX.md or design/SHOT_CONTRACT.md)`,
    );
  if (record[name] !== undefined)
    throw new Error(
      `Guide name "${name}" is authored twice; one name serves one document.`,
    );
  record[name] = readFileSync(file, "utf8").replaceAll("\r\n", "\n").trim();
}

const sorted = Object.fromEntries(
  Object.keys(record)
    .sort()
    .map((name) => [name, record[name]]),
);

const out =
  `// GENERATED by build/prompt.mjs from packages/mcp/prompts/**/*.md\n` +
  `// Do not edit by hand; edit the source markdown and re-run \`pnpm build:prompt\`.\n` +
  `// Gitignored: this file is rebuilt on every install ("prepare") and build.\n\n` +
  `/** Guide content for AutoMovieApplication.getGuideDocument, keyed by served guide name (an area's INDEX.md serves under the area's own name). */\n` +
  `export const AUTOMOVIE_GUIDE_CONSTANT = {\n` +
  Object.entries(sorted)
    .map(([name, content]) => `  ${name}:\n    ${JSON.stringify(content)},`)
    .join("\n") +
  `\n} as const;\n`;

writeFileSync(OUT_FILE, out, "utf8");
console.log(`wrote ${files.length} topic(s) -> ${OUT_FILE}`);
