const contractClaim = (
  name: string,
  files: string[],
  requirements: string[],
  specifications: string[],
): ITtscEvidenceGraphConfig["claims"][number] => {
  const references = (documents: string[]) => [
    {
      type: "markdown" as const,
      root: "../../docs",
      files: documents.filter((file) => file.endsWith("/README.md")),
      symbol: ["h2", "h3"] as const,
    },
    {
      type: "markdown" as const,
      root: "../../docs",
      files: documents.filter((file) => !file.endsWith("/README.md")),
      symbol: ["h3"] as const,
    },
  ];

  return {
    name,
    type: "typescript",
    files,
    symbol: ["type", "function", "property"],
    reference: [...references(requirements), ...references(specifications)],
  };
};

