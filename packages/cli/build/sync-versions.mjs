// Regenerate src/templateVersions.ts from the monorepo's real dependency
// versions, so a scaffolded project's deps can never drift from what this repo
// actually ships (the pattern autobe-mcp uses: bake the versions into the
// published package at build time, since the standalone package cannot read the
// workspace catalog at runtime). Run from `build` and `prepare`.
//
// The resolution rules live in templateVersions.mjs so the repository-local
// experimental sandbox generator reads the same values instead of parsing this
// script's own output back out.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { resolveTemplateVersions } from "./templateVersions.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));

// Emit unquoted identifier keys + double-quoted values so the generated file
// is already prettier-canonical (the repo's `format:check` would otherwise flag
// JSON.stringify's quoted keys).
const entries = Object.entries(resolveTemplateVersions())
  .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
  .join("\n");
const body = `// GENERATED by build/sync-versions.mjs from the workspace. Do not edit by hand.
// Bump the package versions / catalog and re-run \`pnpm run build:versions\`.

/**
 * Dependency versions baked into the scaffold, kept in sync with this repo.
 *
 * @evidence requirements/agent-authoring/project-ownership.md#agent-portable-authoring Pins the documented toolchain inputs a generated project needs in a new checkout.
 * @evidence specifications/authoring-and-authority/source-authority-and-derivation.md#spec-authoring-source-input Emits explicit dependency versions instead of reading undeclared host state.
 */
export const AUTOMOVIE_TEMPLATE_VERSIONS: Record<string, string> = {
${entries}
};
`;

const target = resolve(HERE, "../src/templateVersions.ts");
writeFileSync(target, body, "utf8");
process.stdout.write(`synced template versions → ${target}\n`);
